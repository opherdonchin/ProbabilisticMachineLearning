#!/usr/bin/env bash
# Vendor + track a SeaSlides theme.
# Usage: ./sync-themes.sh THEME [COMMAND] [--offline] [--force]
#        ./sync-themes.sh COMMAND THEME [--offline] [--force]
set -euo pipefail
cd "$(dirname "$0")"

# Format: repository URL|repository ref|theme subpath within the repository.
# DEST, CACHE, ENVFILE, and MANIFEST are derived from the selected theme name.
declare -Ar THEMES=(
  [tensor-field]="https://github.com/touying-typ/seaslides.git|main|skills/seaslides-typst-slides-skill/templates/themes/custom-rich/tensor-field"
  [ruled-page]="https://github.com/touying-typ/seaslides.git|main|skills/seaslides-typst-slides-skill/templates/themes/custom-plain/ruled-page"
)

die() { printf 'error: %s\n' "$*" >&2; exit 1; }
note() { printf '%s\n' "$*"; }
theme_names() { printf '%s' "${!THEMES[*]}"; }
usage() {
  cat <<EOF
Usage: ./sync-themes.sh THEME [COMMAND] [--offline] [--force]
       ./sync-themes.sh COMMAND THEME [--offline] [--force]

Themes:   $(theme_names)
Commands: status (default), install, update, check, sync
EOF
}

OFFLINE=0
FORCE=0
POSITIONAL=()
for arg in "$@"; do
  case "$arg" in
    --offline) OFFLINE=1 ;;
    --force)   FORCE=1 ;;
    -h|--help) usage; exit 0 ;;
    --*)       die "unknown option: $arg" ;;
    *)         POSITIONAL+=("$arg") ;;
  esac
done

case "${#POSITIONAL[@]}" in
  1)
    [[ ! ${POSITIONAL[0]} =~ ^(status|install|update|check|sync)$ ]] || {
      usage >&2
      die "theme is required"
    }
    THEME=${POSITIONAL[0]}
    CMD=status
    ;;
  2)
    if [[ ${POSITIONAL[0]} =~ ^(status|install|update|check|sync)$ ]]; then
      CMD=${POSITIONAL[0]}
      THEME=${POSITIONAL[1]}
    else
      THEME=${POSITIONAL[0]}
      CMD=${POSITIONAL[1]}
    fi
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac

[[ -v "THEMES[$THEME]" ]] || die "unknown theme: $THEME (choose one of: $(theme_names))"
IFS='|' read -r REPO_URL REPO_REF SUBPATH <<< "${THEMES[$THEME]}"

DEST="themes/$THEME"
CACHE=".cache/theme-sources/$THEME"
ENVFILE="$DEST/.upstream.env"
MANIFEST="$DEST/.upstream.sha256"

installed()  { [[ -d $DEST && -n $(ls -A "$DEST" 2>/dev/null) ]]; }
local_tree() { [[ -f $ENVFILE ]] && . "$ENVFILE" && printf '%s' "${UPSTREAM_TREE:-}"; }

fetch_cache() {
  (( OFFLINE )) && die "need network for this operation (drop --offline)"
  if [[ ! -d $CACHE/.git ]]; then
    mkdir -p "$(dirname "$CACHE")"
    git clone --quiet --filter=blob:none --sparse --depth 1 \
        --branch "$REPO_REF" "$REPO_URL" "$CACHE"
    git -C "$CACHE" sparse-checkout set "$SUBPATH"
  else
    git -C "$CACHE" fetch --quiet --depth 1 origin "$REPO_REF"
    git -C "$CACHE" reset --quiet --hard FETCH_HEAD
  fi
  [[ -d $CACHE/$SUBPATH ]] || die "upstream path not found: $SUBPATH
The seaslides repo layout has changed. Fix SUBPATH by hand; not guessing."
}

upstream_ids() {          # sets U_COMMIT, U_TREE
  U_COMMIT=$(git -C "$CACHE" rev-parse HEAD)
  U_TREE=$(git -C "$CACHE" rev-parse "HEAD:$SUBPATH")
}

# sha256 manifest of everything we vendored, so local edits are detectable
write_manifest() {
  ( cd "$DEST" && find . -type f \
      ! -name '.upstream.env' ! -name '.upstream.sha256' ! -name 'UPSTREAM.md' \
      -print0 | sort -z | xargs -0 sha256sum ) > "$MANIFEST"
}
drifted() {
  [[ -f $MANIFEST ]] || return 1
  ( cd "$DEST" && sha256sum --quiet -c "$(basename "$MANIFEST")" ) >/dev/null 2>&1 \
    && return 1 || return 0
}

vendor() {
  upstream_ids
  local tmp; tmp=$(mktemp -d)
  cp -a "$CACHE/$SUBPATH/." "$tmp/"
  [[ -f $CACHE/LICENSE ]] && cp -a "$CACHE/LICENSE" "$tmp/LICENSE.upstream"
  mkdir -p "$(dirname "$DEST")"
  if [[ -d $DEST ]]; then
    if ! mv "$DEST" "$DEST.old.$$"; then
      die "cannot move $DEST aside — a file is probably open in an editor or viewer. Close it and retry."
    fi
  fi
  mv "$tmp" "$DEST"
  rm -rf "$DEST.old.$$" 2>/dev/null || true

  local now; now=$(date -Iseconds)
  cat > "$ENVFILE" <<EOF
UPSTREAM_COMMIT=$U_COMMIT
UPSTREAM_TREE=$U_TREE
UPSTREAM_REF=$REPO_REF
UPSTREAM_PULLED=$now
EOF
  cat > "$DEST/UPSTREAM.md" <<EOF
# Upstream provenance — $THEME

| Field | Value |
|---|---|
| Source | $REPO_URL |
| Path | \`$SUBPATH\` |
| Ref | \`$REPO_REF\` |
| Commit | \`$U_COMMIT\` |
| Subtree hash | \`$U_TREE\` |
| Pulled | $now |
| License | see \`LICENSE.upstream\` |

Generated by \`sync-themes.sh\`. **Do not edit files in this directory** —
keep course overrides outside \`$DEST\` so upstream diffs stay readable.
EOF
  write_manifest
  note "vendored $U_TREE (commit ${U_COMMIT:0:12}) -> $DEST"
}

case "$CMD" in
  install)
    installed && die "$DEST already populated; use 'update'"
    fetch_cache; vendor ;;

  update)
    installed || die "nothing installed; use 'install'"
    if drifted && (( ! FORCE )); then
      die "local modifications detected under $DEST — refusing to overwrite.
Move your changes outside $DEST, or re-run with --force."
    fi
    fetch_cache; upstream_ids
    if [[ $U_TREE == "$(local_tree)" ]]; then
      note "already current ($U_TREE)"; exit 0
    fi
    note "updating: $(local_tree) -> $U_TREE"
    vendor ;;

  check)   # CI / pre-flight: non-zero if stale or drifted
    installed || { note "MISSING"; exit 2; }
    drifted && { note "DRIFT: local edits under $DEST"; exit 3; }
    (( OFFLINE )) && { note "OK (offline, freshness unchecked)"; exit 0; }
    fetch_cache; upstream_ids
    [[ $U_TREE == "$(local_tree)" ]] && note "OK ($U_TREE)" || { note "STALE"; exit 4; } ;;

  sync)    # safe default: install if absent, report-only if stale
    if ! installed; then fetch_cache; vendor; exit 0; fi
    (( OFFLINE )) && { note "present (offline)"; exit 0; }
    fetch_cache; upstream_ids
    if [[ $U_TREE != "$(local_tree)" ]]; then
      note "NOTE: upstream theme has changed (${U_TREE:0:12}). Run './sync-themes.sh $THEME update' when you want it."
    else note "current"; fi ;;

  status)
    installed || { note "not installed"; exit 0; }
    . "$ENVFILE" 2>/dev/null || true
    note "commit : ${UPSTREAM_COMMIT:-?}"
    note "tree   : ${UPSTREAM_TREE:-?}"
    note "pulled : ${UPSTREAM_PULLED:-?}"
    drifted && note "local  : MODIFIED" || note "local  : clean"
    (( OFFLINE )) && exit 0
    fetch_cache; upstream_ids
    [[ $U_TREE == "${UPSTREAM_TREE:-}" ]] && note "remote : current" || note "remote : NEWER ($U_TREE)" ;;

  *) die "unknown command: $CMD" ;;
esac
